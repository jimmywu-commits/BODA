'use strict';

/* Rebuild after editing blocks/index.js or any listed block.json.
 * node tools/build-block-catalogue.js [--check]
 * The generated JS also works when opening BODA directly with file://.
 */
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '..');
const target = path.join(root, 'blocks', 'catalogue.bundle.js');
const enginePath = path.join(root, 'core', 'core-engine.js');

function build() {
  const manifest = fs.readFileSync(path.join(root, 'blocks', 'index.js'), 'utf8');
  const match = manifest.match(/_bn_blocks_manifest_cb\s*\(\s*(\[[\s\S]*\])\s*\)\s*;?\s*$/);
  if (!match) throw new Error('blocks/index.js 必須是 _bn_blocks_manifest_cb(JSON 陣列)');
  const ids = JSON.parse(match[1]);
  if (!Array.isArray(ids) || new Set(ids).size !== ids.length) throw new Error('版位清單必須是無重複 ID 的陣列');
  const schemas = ids.map(id => {
    if (typeof id !== 'string' || !/^[a-zA-Z0-9_-]+$/.test(id)) throw new Error('不合法的版位 ID：' + id);
    const schema = JSON.parse(fs.readFileSync(path.join(root, 'blocks', id, 'block.json'), 'utf8'));
    if (!schema || schema.id !== id) throw new Error(id + '/block.json 的 ID 不相符');
    return schema;
  });
  const content = JSON.stringify({ ids, schemas });
  const version = crypto.createHash('sha256').update(content).digest('hex').slice(0, 16);
  const payload = JSON.stringify({ format: 'boda-block-catalogue', version, ids, schemas });
  const text = '/* Generated by tools/build-block-catalogue.js. Do not edit; source: blocks/index.js + block.json. */\n' +
    '(function(root){var node=document.currentScript;var base=new URL(".",node&&node.src||document.baseURI).href;' +
    'var catalogues=root.BN_BLOCK_CATALOGUES||(root.BN_BLOCK_CATALOGUES=Object.create(null));catalogues[base]=' + payload + ';})(window);\n';
  return { text, version, count: ids.length };
}

const result = build();
const engine = fs.readFileSync(enginePath, 'utf8');
const release = "var BN_BLOCKS_RELEASE = 'blocks-" + result.version + "';";
if (!/var BN_BLOCKS_RELEASE = '[^']+';/.test(engine)) throw new Error('core-engine.js 缺少 BN_BLOCKS_RELEASE');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== result.text || !engine.includes(release)) {
    console.error('版位 bundle 已過期；請執行 node tools/build-block-catalogue.js');
    process.exitCode = 1;
  } else console.log('PASS: ' + result.count + ' 個版位的 bundle 與來源一致（' + result.version + '）');
} else {
  fs.writeFileSync(target, result.text);
  fs.writeFileSync(enginePath, engine.replace(/var BN_BLOCKS_RELEASE = '[^']+';/, release));
  console.log('Built ' + result.count + ' blocks / ' + Buffer.byteLength(result.text) + ' bytes / ' + result.version);
}
